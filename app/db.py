"""Base de datos de evaluaciones, compatible con SQLite local y PostgreSQL."""
import json
import os
import sqlite3
from contextlib import contextmanager
from datetime import datetime, timedelta
from pathlib import Path

RUTA_PREDETERMINADA = Path(__file__).resolve().parent.parent / "datos" / "expedientes.db"
RUTA = Path(os.environ.get("DB_PATH", str(RUTA_PREDETERMINADA)))
BACKEND = os.environ.get("DB_BACKEND", "sqlite").lower()
DATABASE_URL = os.environ.get("DATABASE_URL")


def _con():
    if BACKEND == "postgres":
        if not DATABASE_URL:
            raise RuntimeError(
                "Falta DATABASE_URL. Configurá la conexión PostgreSQL de Supabase "
                "en las variables de entorno de Render."
            )
        try:
            import psycopg
            from psycopg.rows import dict_row
        except ImportError as e:
            raise RuntimeError(
                "Falta psycopg. Instalá las dependencias de requirements.txt."
            ) from e
        return psycopg.connect(DATABASE_URL, row_factory=dict_row, sslmode="require")
    if BACKEND != "sqlite":
        raise RuntimeError(f"DB_BACKEND no reconocido: {BACKEND}")

    RUTA.parent.mkdir(parents=True, exist_ok=True)
    con = sqlite3.connect(RUTA)
    con.row_factory = sqlite3.Row
    return con


@contextmanager
def _conexion():
    con = _con()
    try:
        with con:
            yield con
    finally:
        con.close()


def _ejecutar(con, consulta, parametros=()):
    if BACKEND == "postgres":
        consulta = consulta.replace("?", "%s")
    return con.execute(consulta, parametros)


def iniciar():
    tipo_id = (
        "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
        if BACKEND == "postgres" else "INTEGER PRIMARY KEY AUTOINCREMENT"
    )
    with _conexion() as con:
        _ejecutar(con, f"""CREATE TABLE IF NOT EXISTS evaluaciones (
            id {tipo_id},
            fecha TEXT NOT NULL,
            edad INTEGER NOT NULL,
            diagnostico TEXT NOT NULL,
            practica TEXT NOT NULL,
            estudios TEXT NOT NULL,
            sugerencia TEXT NOT NULL,
            probabilidad REAL NOT NULL,
            version_modelo TEXT NOT NULL,
            decision TEXT,
            fecha_decision TEXT,
            motivo TEXT)""")


def guardar(edad, diagnostico, practica, resultado, version):
    consulta = """INSERT INTO evaluaciones (fecha, edad, diagnostico, practica, estudios,
                  sugerencia, probabilidad, version_modelo)
                 VALUES (?, ?, ?, ?, ?, ?, ?, ?)"""
    if BACKEND == "postgres":
        consulta += " RETURNING id"
    with _conexion() as con:
        cur = _ejecutar(
            con, consulta,
            (datetime.now().isoformat(timespec="seconds"), edad, diagnostico, practica,
             json.dumps(resultado["estudios"], ensure_ascii=False),
             resultado["sugerencia"], resultado["probabilidad"], version),
        )
        nuevo = cur.fetchone()["id"] if BACKEND == "postgres" else cur.lastrowid
    return nuevo


def obtener(id_exp):
    with _conexion() as con:
        fila = _ejecutar(con, "SELECT * FROM evaluaciones WHERE id = ?", (id_exp,)).fetchone()
    return dict(fila) if fila else None


def registrar_decision(id_exp, decision, motivo):
    with _conexion() as con:
        cur = _ejecutar(
            con,
            "UPDATE evaluaciones SET decision = ?, fecha_decision = ?, motivo = ? WHERE id = ?",
            (decision, datetime.now().isoformat(timespec="seconds"), motivo, id_exp),
        )
        return cur.rowcount > 0


def similares(id_exp, diagnostico, practica, limite=10):
    with _conexion() as con:
        filas = _ejecutar(
            con,
            """SELECT id, fecha, diagnostico, practica, sugerencia, decision
               FROM evaluaciones
               WHERE id != ? AND decision IS NOT NULL
                 AND (diagnostico = ? OR practica = ?)
               ORDER BY id DESC LIMIT ?""",
            (id_exp, diagnostico, practica, limite),
        ).fetchall()
    return [dict(f) for f in filas]


def sin_respuesta(dias=3):
    corte = (datetime.now() - timedelta(days=dias)).isoformat(timespec="seconds")
    with _conexion() as con:
        filas = _ejecutar(
            con,
            """SELECT id, fecha, diagnostico, practica, sugerencia FROM evaluaciones
               WHERE decision IS NULL AND fecha < ? ORDER BY fecha""",
            (corte,),
        ).fetchall()
    return [dict(f) for f in filas]


def concordancia():
    with _conexion() as con:
        fila = _ejecutar(
            con,
            """SELECT COUNT(*) AS total,
                      SUM(CASE WHEN sugerencia = decision THEN 1 ELSE 0 END) AS coinciden
               FROM evaluaciones WHERE decision IN ('AUTORIZADO', 'NO_AUTORIZADO')"""
        ).fetchone()
    total, coinciden = fila["total"] or 0, fila["coinciden"] or 0
    return {
        "decididos": total,
        "coinciden": coinciden,
        "concordancia": round(coinciden / total, 3) if total else None,
    }
def historial(limite=200):
    with _conexion() as con:
        filas = _ejecutar(
            con,
            """SELECT id, fecha, edad, diagnostico, practica, estudios, sugerencia,
                      probabilidad, version_modelo, decision, fecha_decision, motivo
               FROM evaluaciones ORDER BY id DESC LIMIT ?""",
            (limite,),
        ).fetchall()
    return [dict(f) for f in filas]